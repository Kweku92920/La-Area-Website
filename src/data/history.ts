const DEPRECATED_AI_ASSET_HASHES = [
  '5c7fc686909035e25b719a139b0fecf29ff6e564',
  'aad0b73c7b58240e26b1bebfa5a028761b72a60d',
  'e27b079c4add9ceb94244479ddb8e22191c59f77',
  'ebcee11989bf0ce95e9b23e6753e31f9fe185eef',
  'dbb52deb4ad39cc38738c23ee21183f789d538d5',
];

function isRealImageUrl(url?: string | null): boolean {
  if (!url) return false;
  return !DEPRECATED_AI_ASSET_HASHES.some((hash) => url.includes(hash));
}

export function mergeHistoryWithSanity(
  fallback: HistoryPageData,
  sanityDoc: Partial<HistoryPageData> | null | undefined,
): HistoryPageData {
  if (!sanityDoc) {
    return fallback;
  }

  return {
    id: sanityDoc.id || fallback.id,
    slug: sanityDoc.slug || fallback.slug,
    kicker: sanityDoc.kicker?.trim() || fallback.kicker,
    title: sanityDoc.title?.trim() || fallback.title,
    subtitle: sanityDoc.subtitle?.trim() || fallback.subtitle,
    intro: sanityDoc.intro?.trim() || fallback.intro,
    heroImage: isRealImageUrl(sanityDoc.heroImage) ? sanityDoc.heroImage! : fallback.heroImage,
    heroImageAlt: sanityDoc.heroImageAlt?.trim() || fallback.heroImageAlt,
    heroImageCaption: sanityDoc.heroImageCaption?.trim() || fallback.heroImageCaption,
    quote:
      sanityDoc.quote?.text?.trim()
        ? {
            text: sanityDoc.quote.text.trim(),
            attribution: sanityDoc.quote.attribution?.trim() || fallback.quote?.attribution || '',
            role: sanityDoc.quote.role?.trim() || fallback.quote?.role || null,
          }
        : fallback.quote,
    stats:
      Array.isArray(sanityDoc.stats) && sanityDoc.stats.length > 0
        ? sanityDoc.stats.filter((s) => s && (s.value || s.label))
        : fallback.stats,
    sections:
      Array.isArray(sanityDoc.sections) && sanityDoc.sections.length > 0
        ? sanityDoc.sections
            .filter((sec) => sec && (sec.title || (sec.paragraphs && sec.paragraphs.length > 0)))
            .map((sec, idx) => ({
              ...sec,
              kicker: sec.kicker || fallback.sections[idx]?.kicker || `Chapter 0${idx + 1}`,
              paragraphs:
                Array.isArray(sec.paragraphs) && sec.paragraphs.length > 0
                  ? sec.paragraphs
                  : fallback.sections[idx]?.paragraphs ?? [],
              image: isRealImageUrl(sec.image)
                ? sec.image!
                : fallback.sections[idx]?.image || null,
              imageAlt: sec.imageAlt || fallback.sections[idx]?.imageAlt || sec.title,
              imageCaption: sec.imageCaption || fallback.sections[idx]?.imageCaption || null,
            }))
        : fallback.sections,
    milestones:
      Array.isArray(sanityDoc.milestones) && sanityDoc.milestones.length > 0
        ? sanityDoc.milestones.filter((m) => m && (m.year || m.title))
        : fallback.milestones,
    leadershipLegacy:
      Array.isArray(sanityDoc.leadershipLegacy) && sanityDoc.leadershipLegacy.length > 0
        ? sanityDoc.leadershipLegacy
            .filter((l) => l && l.name)
            .map((l, idx) => ({
              ...l,
              photo: isRealImageUrl(l.photo)
                ? l.photo!
                : fallback.leadershipLegacy[idx]?.photo || null,
            }))
        : fallback.leadershipLegacy,
    body: Array.isArray(sanityDoc.body) && sanityDoc.body.length > 0 ? sanityDoc.body : fallback.body,
    gallery:
      Array.isArray(sanityDoc.gallery) &&
      sanityDoc.gallery.filter((g) => isRealImageUrl(g?.url)).length > 0
        ? sanityDoc.gallery.filter((g) => isRealImageUrl(g?.url))
        : fallback.gallery,
    updatedAt: sanityDoc.updatedAt ?? fallback.updatedAt ?? null,
  };
}
